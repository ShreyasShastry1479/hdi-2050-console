"""Ethnic composition baseline and 2050 projection for the 193 UNDP countries.

The baseline shares (ETHNIC_COMPOSITION_2024) approximate current ethnic
composition drawn from national censuses and the CIA World Factbook
(c. 2023-2024). Shares are percentages that may not sum to 100; the remainder
is assigned to an "Other" bucket by :func:`normalise_composition`.

Projection model
----------------
Each ethnic group's population is compounded year-by-year with a deviation
``dev`` from the national population growth rate (which cancels out when
computing shares, so national growth only matters for absolute group
population sizes):

    P_g(t+1) = P_g(t) * (1 + dev_g(t))

``dev_g`` is the annual, in-percentage-points-above-national growth advantage
of group ``g``. It is derived from an ethnic profile (see ETHNIC_PROFILES):

- ``high_fertility`` : groups whose total fertility exceeds the national
  average (e.g. Muslim minorities in Western Europe, Arabs in Israel,
  Kurdish in Turkey) -> positive deviation that decays as TFRs converge.
- ``immigrant``      : groups whose numbers are sustained by inward migration
  (expat workers in the Gulf, foreign-born communities) -> positive
  deviation scaled by the migration scenario.
- ``low_fertility``  : groups with below-national fertility (e.g. Japanese,
  secular European-descent groups in immigrant countries) -> negative
  deviation.
- ``assimilating``   : minority groups with high out-marriage / identity
  shift, losing a fraction of population each year to the anchor group.

A per-country ``assimilation_rate`` additionally shifts a small share of every
minority group's population to the largest (anchor) group each year, modelling
intermarriage and identity convergence.

This is a scenario tool, not a statistical forecast: every parameter is
explicit and adjustable (see :func:`project_ethnic_composition`).
"""

